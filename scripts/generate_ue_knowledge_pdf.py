def build_pdf() -> Path:
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    doc = SimpleDocTemplate(
        str(OUTPUT_PATH),
        pagesize=letter,
        leftMargin=0.75 * inch,
        rightMargin=0.75 * inch,
        topMargin=0.75 * inch,
        bottomMargin=0.85 * inch,
        title="Kinora Upper Extremity AI Orientation",
        author="Kinora AI Training",
    )
    styles = build_styles()
    story: list = []

    # Title page
    story.append(Spacer(1, 1.5 * inch))
    story.append(Paragraph("Kinora Upper Extremity", styles["title"]))
    story.append(Paragraph("AI Clinical Orientation Database", styles["title"]))
    story.append(Spacer(1, 0.3 * inch))
    story.append(Paragraph(
        "Structured reference for RAG / AI-assisted physiotherapy consultation",
        styles["subtitle"],
    ))
    story.append(Spacer(1, 0.2 * inch))
    story.append(Paragraph("Upper Extremity: Anatomy, Examination, Pathology &amp; Rehabilitation", styles["subtitle"]))
    story.append(Spacer(1, 0.5 * inch))
    story.append(Paragraph("Version 1.0 — Kinora Admin Conocimientos Upload", styles["subtitle"]))
    story.append(PageBreak())

    # Disclaimer
    add_section(story, styles, "Disclaimer")
    story.append(Paragraph(
        "This document is an educational orientation resource for Kinora AI clinical consultation support. "
        "It is NOT a substitute for professional clinical judgment, direct patient examination, or "
        "licensed medical/physiotherapy care. Content reflects established musculoskeletal medicine "
        "and sports rehabilitation concepts but must be verified against current peer-reviewed literature, "
        "local protocols, and individual patient presentation. Always screen for red flags requiring "
        "urgent medical referral. Diagnostic sensitivity/specificity values are approximate and vary by study.",
        styles["disclaimer"],
    ))
    story.append(Spacer(1, 12))

    # TOC
    add_section(story, styles, "Table of Contents")
    for item in TOC_SECTIONS:
        story.append(Paragraph(f"• {esc(item)}", styles["toc"]))
    story.append(PageBreak())

    # Section builders
    sections_data = [
        ("1. Bones", BONES),
        ("2. Muscles", MUSCLES),
        ("3. Ligaments", LIGAMENTS),
        ("4. Tendons", TENDONS),
        ("5. Nerves", NERVES),
        ("6. Joints", JOINTS),
        ("7. Biomechanics", BIOMECHANICS),
    ]

    for section_title, records in sections_data:
        add_section(story, styles, section_title)
        story.append(Spacer(1, 6))
        for name, fields in records:
            add_record(story, styles, name, fields)
        story.append(PageBreak())

    # Clinical exam
    add_section(story, styles, "8. Clinical Examination Template")
    add_record(story, styles, CLINICAL_EXAM["Template Name"], CLINICAL_EXAM)
    story.append(PageBreak())

    # Special tests
    add_section(story, styles, "9. Special Tests")
    for name, fields in SPECIAL_TESTS:
        add_record(story, styles, name, fields)
    story.append(PageBreak())

    # Pathologies
    add_section(story, styles, "10. Pathologies")
    for name, fields in PATHOLOGIES:
        add_record(story, styles, name, fields)
    story.append(PageBreak())

    # Rehab phases
    add_section(story, styles, "11. Rehabilitation Phases")
    for name, fields in REHAB_PHASES:
        add_record(story, styles, name, fields)
    story.append(PageBreak())

    # Exercises
    add_section(story, styles, "12. Exercise Library")
    for name, fields in EXERCISES:
        add_record(story, styles, name, fields)
    story.append(PageBreak())

    # RTS
    add_section(story, styles, "13. Return to Sport")
    for name, fields in RTS_RECORDS:
        add_record(story, styles, name, fields)
    story.append(PageBreak())

    # Imaging
    add_section(story, styles, "14. Imaging")
    for name, fields in IMAGING:
        add_record(story, styles, name, fields)
    story.append(Spacer(1, 12))

