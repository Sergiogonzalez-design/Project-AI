def pathology_record(pid: str, name: str, **kwargs: Any) -> tuple[str, dict[str, Any]]:
    fields = {"ID": pid, "Name": name}
    for k in PATHOLOGY_FIELDS[2:]:
        key = k.replace(" ", "_").replace("-", "_").replace("/", "_").replace("(", "").replace(")", "")
        fields[k] = kwargs.get(key, kwargs.get(k, "See references"))
    return name, fields

